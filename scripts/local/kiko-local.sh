#!/usr/bin/env bash
# Kiko local test environment (macOS, native services, no Docker).
#
# Everything runs on this Mac only, bound to 127.0.0.1, with Kiko-only data:
#   postgres  dedicated PostgreSQL 16 cluster   127.0.0.1:55432  (db/user kiko_local)
#   redis     dedicated Redis                   127.0.0.1:56379  (password protected)
#   mailpit   email capture (nothing leaves)    SMTP 127.0.0.1:56025, UI http://127.0.0.1:58025
#   api       FastAPI (uvicorn)                 http://localhost:8000
#   worker    Celery execution worker
#   outbox    outbox dispatcher
#   mailer    transactional email dispatcher -> Mailpit
#   web       Next.js web client (email links)  http://localhost:3000
#
# Data, secrets and logs live in $KIKO_LOCAL_HOME (default ~/.kiko-local) and survive
# stop/restart. This script never deletes that directory.
#
# Usage: scripts/local/kiko-local.sh <command> [service...]
#   start [svc...]    start all services (or the ones named); runs migrations first
#   stop [svc...]     stop services gracefully (data is kept)
#   restart [svc...]  stop then start
#   status            show each service and the API health
#   logs [svc] [-f]   show (or follow) a service log; no service = list log files
#   migrate           apply Alembic migrations and seed the built-in agents
#   test              run the backend smoke test (fictitious data) against the running stack
#   test-persisted    after a restart: sign in again with the account the last test created
#   desktop-e2e       run the real macOS app journey (debug build) against this backend
#   open-link <url>   open an emailed http://localhost:3000/... link in the Kiko macOS app
#   psql              open psql on the Kiko local database
#   env               print the non-secret configuration
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
API_DIR="$REPO/apps/api"
WEB_DIR="$REPO/apps/web"
H="${KIKO_LOCAL_HOME:-$HOME/.kiko-local}"
PG_BIN="${KIKO_LOCAL_PG_BIN:-/opt/homebrew/opt/postgresql@16/bin}"
PY="${KIKO_LOCAL_PYTHON:-$REPO/.venv/bin/python}"
PG_PORT="${KIKO_LOCAL_PG_PORT:-55432}"
REDIS_PORT="${KIKO_LOCAL_REDIS_PORT:-56379}"
SMTP_PORT="${KIKO_LOCAL_SMTP_PORT:-56025}"
MAIL_UI_PORT="${KIKO_LOCAL_MAIL_UI_PORT:-58025}"
API_PORT="${KIKO_LOCAL_API_PORT:-8000}"
WEB_PORT="${KIKO_LOCAL_WEB_PORT:-3000}"
ALL_SERVICES=(postgres redis mailpit api worker outbox mailer web)

RUN="$H/run"
LOGS="$H/logs"
SECRETS="$H/secrets.env"
OVERRIDES="$H/overrides.env"

say() { printf '%s\n' "$*"; }
die() { printf 'kiko-local: %s\n' "$*" >&2; exit 1; }

port_busy() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }

wait_port() { # port seconds
  local i
  for ((i = 0; i < $2 * 4; i++)); do port_busy "$1" && return 0; sleep 0.25; done
  return 1
}

pid_of() { local f="$RUN/$1.pid"; [ -f "$f" ] && cat "$f" || true; }

alive() { local p; p="$(pid_of "$1")"; [ -n "$p" ] && kill -0 "$p" 2>/dev/null; }

kill_tree() { # pid signal
  local child
  for child in $(pgrep -P "$1" 2>/dev/null || true); do kill_tree "$child" "$2"; done
  kill "-$2" "$1" 2>/dev/null || true
}

ensure_tools() {
  [ -x "$PG_BIN/initdb" ] || die "PostgreSQL 16 not found at $PG_BIN (brew install postgresql@16)"
  command -v redis-server >/dev/null || die "redis-server not found (brew install redis)"
  command -v mailpit >/dev/null || die "mailpit not found (brew install mailpit)"
  [ -x "$PY" ] || die "Python venv not found at $PY (see docs/desktop/KIKO-LOCAL-TEST-ENVIRONMENT.md)"
}

# --- one-time initialisation (idempotent) ---------------------------------------------
init_home() {
  mkdir -p "$H" "$RUN" "$LOGS" "$H/redis" "$H/mailpit" "$H/smoke"
  chmod 700 "$H"
  if [ ! -f "$SECRETS" ]; then
    umask 077
    {
      echo "# Generated by kiko-local.sh for this Mac only. Not used anywhere else."
      echo "KIKO_LOCAL_PG_PASSWORD=$(openssl rand -hex 24)"
      echo "KIKO_LOCAL_REDIS_PASSWORD=$(openssl rand -hex 24)"
      echo "AUTH_SECRET_KEY=$(openssl rand -hex 32)"
    } > "$SECRETS"
    umask 022
  fi
  if [ ! -f "$OVERRIDES" ]; then
    cat > "$OVERRIDES" <<'EOF'
# Local overrides for the Kiko local test environment (read after the defaults).
# Restart the API/worker after editing: scripts/local/kiko-local.sh restart api worker outbox
#
# AI provider. The backend supports AI_PROVIDER=openai (real) and fake (automated tests
# only). Without a key, Kiko AI / Supervisor planning report "AI provider unavailable".
# Using a real key is a paid OpenAI service: only add one you are authorised to use.
# OPENAI_API_KEY=
# OPENAI_MODEL=gpt-5.4-mini
EOF
    chmod 600 "$OVERRIDES"
  fi
}

load_secrets() {
  # shellcheck disable=SC1090
  set -a; . "$SECRETS"; set +a
}

# Environment shared by the API and background processes.
write_api_env() {
  load_secrets
  umask 077
  cat > "$RUN/api.env" <<EOF
APP_NAME="Kiko API (local)"
APP_ENV=development
API_PORT=$API_PORT
WEB_ORIGINS=http://localhost:$WEB_PORT,http://127.0.0.1:$WEB_PORT
TRUSTED_HOSTS=localhost,127.0.0.1
DATABASE_URL=postgresql+psycopg://kiko_local:$KIKO_LOCAL_PG_PASSWORD@127.0.0.1:$PG_PORT/kiko_local
REDIS_URL=redis://:$KIKO_LOCAL_REDIS_PASSWORD@127.0.0.1:$REDIS_PORT/0
CELERY_BROKER_URL=redis://:$KIKO_LOCAL_REDIS_PASSWORD@127.0.0.1:$REDIS_PORT/1
AUTH_SECRET_KEY=$AUTH_SECRET_KEY
AUTH_COOKIE_SECURE=false
AUTH_COOKIE_SAMESITE=lax
AUTH_REQUIRE_EMAIL_VERIFICATION=true
AUTH_RATE_LIMIT_ENABLED=true
PUBLIC_WEB_URL=http://localhost:$WEB_PORT
TRANSACTIONAL_EMAIL_ENABLED=true
TRANSACTIONAL_EMAIL_FROM=kiko-local@example.com
SMTP_HOST=127.0.0.1
SMTP_PORT=$SMTP_PORT
SMTP_STARTTLS=false
SMTP_USERNAME=
SMTP_PASSWORD=
AI_PROVIDER=openai
OPENAI_API_KEY=
EMAIL_INTEGRATION_ENABLED=false
CALENDAR_INTEGRATION_ENABLED=false
GITHUB_INTEGRATION_ENABLED=false
CODEX_INTEGRATION_ENABLED=false
OUTBOX_POLL_INTERVAL_SECONDS=2
EOF
  grep -E '^[A-Z_]+=' "$OVERRIDES" >> "$RUN/api.env" || true
  umask 022
}

# Run a command with the API environment loaded, from apps/api.
with_api_env() {
  (set -a; . "$RUN/api.env"; set +a; cd "$API_DIR"; "$@")
}

pg_env() { load_secrets; export PGPASSWORD="$KIKO_LOCAL_PG_PASSWORD"; }

init_postgres() {
  [ -f "$H/postgres/PG_VERSION" ] && return 0
  say "initialising dedicated PostgreSQL cluster in $H/postgres"
  load_secrets
  local pw; pw="$(mktemp)"
  printf '%s\n' "$KIKO_LOCAL_PG_PASSWORD" > "$pw"
  LC_ALL=C LANG=C "$PG_BIN/initdb" -D "$H/postgres" -U kiko_local --pwfile="$pw" \
    --auth=scram-sha-256 -E UTF8 --locale=C > "$LOGS/postgres-initdb.log"
  rm -f "$pw"
  cat >> "$H/postgres/postgresql.conf" <<EOF

# kiko-local
port = $PG_PORT
listen_addresses = '127.0.0.1'
unix_socket_directories = '$RUN'
EOF
}

# --- services --------------------------------------------------------------------------
start_bg() { # name logfile command...
  local name="$1" log="$2"; shift 2
  (exec nohup "$@" >> "$log" 2>&1 < /dev/null) &
  echo $! > "$RUN/$name.pid"
}

start_postgres() {
  init_postgres
  if "$PG_BIN/pg_ctl" -D "$H/postgres" status >/dev/null 2>&1; then say "postgres: already running"; return; fi
  port_busy "$PG_PORT" && die "port $PG_PORT is used by another process; set KIKO_LOCAL_PG_PORT"
  LC_ALL=C LANG=C "$PG_BIN/pg_ctl" -D "$H/postgres" -l "$LOGS/postgres.log" -w -t 30 start > /dev/null
  pg_env
  if ! "$PG_BIN/psql" -h 127.0.0.1 -p "$PG_PORT" -U kiko_local -d postgres -tAc \
      "select 1 from pg_database where datname='kiko_local'" | grep -q 1; then
    "$PG_BIN/createdb" -h 127.0.0.1 -p "$PG_PORT" -U kiko_local kiko_local
  fi
  say "postgres: running on 127.0.0.1:$PG_PORT"
}

stop_postgres() {
  if "$PG_BIN/pg_ctl" -D "$H/postgres" status >/dev/null 2>&1; then
    "$PG_BIN/pg_ctl" -D "$H/postgres" -m fast -w stop > /dev/null && say "postgres: stopped"
  else
    say "postgres: not running"
  fi
}

redis_cli() { load_secrets; REDISCLI_AUTH="$KIKO_LOCAL_REDIS_PASSWORD" redis-cli -h 127.0.0.1 -p "$REDIS_PORT" "$@"; }

start_redis() {
  if redis_cli ping 2>/dev/null | grep -q PONG; then say "redis: already running"; return; fi
  port_busy "$REDIS_PORT" && die "port $REDIS_PORT is used by another process; set KIKO_LOCAL_REDIS_PORT"
  load_secrets
  umask 077
  cat > "$RUN/redis.conf" <<EOF
bind 127.0.0.1
port $REDIS_PORT
protected-mode yes
requirepass $KIKO_LOCAL_REDIS_PASSWORD
dir $H/redis
appendonly yes
appendfsync everysec
save 60 1
daemonize yes
pidfile $RUN/redis.pid
logfile $LOGS/redis.log
EOF
  umask 022
  redis-server "$RUN/redis.conf"
  wait_port "$REDIS_PORT" 10 || die "redis did not start (see $LOGS/redis.log)"
  say "redis: running on 127.0.0.1:$REDIS_PORT"
}

stop_redis() {
  if redis_cli ping 2>/dev/null | grep -q PONG; then
    redis_cli shutdown >/dev/null 2>&1 || true
    say "redis: stopped (data saved)"
  else
    say "redis: not running"
  fi
}

start_mailpit() {
  if alive mailpit; then say "mailpit: already running"; return; fi
  port_busy "$SMTP_PORT" && die "port $SMTP_PORT is busy; set KIKO_LOCAL_SMTP_PORT"
  port_busy "$MAIL_UI_PORT" && die "port $MAIL_UI_PORT is busy; set KIKO_LOCAL_MAIL_UI_PORT"
  start_bg mailpit "$LOGS/mailpit.log" mailpit --database "$H/mailpit/mailpit.db" \
    --smtp "127.0.0.1:$SMTP_PORT" --listen "127.0.0.1:$MAIL_UI_PORT" --max 2000
  wait_port "$MAIL_UI_PORT" 10 || die "mailpit did not start (see $LOGS/mailpit.log)"
  say "mailpit: SMTP 127.0.0.1:$SMTP_PORT, inbox http://127.0.0.1:$MAIL_UI_PORT"
}

migrate() {
  write_api_env
  say "migrations: alembic upgrade head"
  with_api_env "$PY" -m alembic upgrade head >> "$LOGS/migrate.log" 2>&1 \
    || die "migration failed (see $LOGS/migrate.log)"
  with_api_env "$PY" -m app.scripts.seed_agents >> "$LOGS/migrate.log" 2>&1 \
    || die "agent seed failed (see $LOGS/migrate.log)"
  say "migrations: at $(with_api_env "$PY" -m alembic current 2>/dev/null | tail -1)"
}

start_api() {
  if alive api; then say "api: already running"; return; fi
  port_busy "$API_PORT" && die "port $API_PORT is used by another process"
  write_api_env
  start_bg api "$LOGS/api.log" bash -c "set -a; . '$RUN/api.env'; set +a; cd '$API_DIR'; \
    exec '$PY' -m uvicorn app.main:app --host 127.0.0.1 --port $API_PORT"
  local i
  for ((i = 0; i < 60; i++)); do
    curl -fsS "http://127.0.0.1:$API_PORT/health" >/dev/null 2>&1 && break
    alive api || die "api exited (see $LOGS/api.log)"
    sleep 0.5
  done
  curl -fsS "http://127.0.0.1:$API_PORT/health" >/dev/null || die "api not healthy (see $LOGS/api.log)"
  say "api: http://localhost:$API_PORT"
}

start_worker() {
  if alive worker; then say "worker: already running"; return; fi
  write_api_env
  start_bg worker "$LOGS/worker.log" bash -c "set -a; . '$RUN/api.env'; set +a; cd '$API_DIR'; \
    exec '$PY' -m celery -A app.execution.celery_app:celery_app worker \
      --loglevel=INFO --pool=solo --hostname=kiko-local@%h"
  say "worker: started"
}

start_outbox() {
  if alive outbox; then say "outbox: already running"; return; fi
  write_api_env
  start_bg outbox "$LOGS/outbox.log" bash -c "set -a; . '$RUN/api.env'; set +a; cd '$API_DIR'; \
    exec '$PY' -m app.scripts.run_outbox_dispatcher"
  say "outbox: started"
}

start_mailer() {
  if alive mailer; then say "mailer: already running"; return; fi
  write_api_env
  start_bg mailer "$LOGS/mailer.log" bash -c "set -a; . '$RUN/api.env'; set +a; cd '$API_DIR'; \
    exec '$PY' -m app.scripts.run_transactional_email_dispatcher"
  say "mailer: started"
}

start_web() {
  if alive web; then say "web: already running"; return; fi
  port_busy "$WEB_PORT" && die "port $WEB_PORT is used by another process; set KIKO_LOCAL_WEB_PORT"
  [ -x "$WEB_DIR/node_modules/.bin/next" ] || die "web dependencies missing (run pnpm install)"
  start_bg web "$LOGS/web.log" bash -c "cd '$WEB_DIR'; \
    NEXT_PUBLIC_API_URL=http://localhost:$API_PORT exec ./node_modules/.bin/next dev \
      --hostname 127.0.0.1 --port $WEB_PORT"
  wait_port "$WEB_PORT" 60 || die "web did not start (see $LOGS/web.log)"
  say "web: http://localhost:$WEB_PORT"
}

stop_process() { # name grace-seconds
  local name="$1" grace="$2" p i
  if ! alive "$name"; then say "$name: not running"; rm -f "$RUN/$name.pid"; return; fi
  p="$(pid_of "$name")"
  kill_tree "$p" TERM
  for ((i = 0; i < grace * 4; i++)); do kill -0 "$p" 2>/dev/null || break; sleep 0.25; done
  if kill -0 "$p" 2>/dev/null; then kill_tree "$p" KILL; fi
  rm -f "$RUN/$name.pid"
  say "$name: stopped"
}

start_one() {
  case "$1" in
    postgres) start_postgres ;; redis) start_redis ;; mailpit) start_mailpit ;;
    api) start_api ;; worker) start_worker ;; outbox) start_outbox ;;
    mailer) start_mailer ;; web) start_web ;;
    *) die "unknown service: $1 (one of: ${ALL_SERVICES[*]})" ;;
  esac
}

stop_one() {
  case "$1" in
    postgres) stop_postgres ;; redis) stop_redis ;;
    mailpit) stop_process mailpit 5 ;; api) stop_process api 15 ;;
    worker) stop_process worker 30 ;; outbox) stop_process outbox 15 ;;
    mailer) stop_process mailer 15 ;; web) stop_process web 10 ;;
    *) die "unknown service: $1 (one of: ${ALL_SERVICES[*]})" ;;
  esac
}

cmd_start() {
  ensure_tools; init_home
  local services=("$@")
  if [ ${#services[@]} -eq 0 ]; then
    start_postgres; start_redis; start_mailpit; migrate
    start_api; start_worker; start_outbox; start_mailer; start_web
    say ""; say "Kiko local API: http://localhost:$API_PORT   (Kiko → Server Connection…)"
    say "Email inbox:    http://127.0.0.1:$MAIL_UI_PORT"
  else
    local s; for s in "${services[@]}"; do start_one "$s"; done
  fi
}

cmd_stop() {
  init_home
  local services=("$@") i
  if [ ${#services[@]} -eq 0 ]; then
    # reverse order: clients first, data stores last
    for ((i = ${#ALL_SERVICES[@]} - 1; i >= 0; i--)); do stop_one "${ALL_SERVICES[$i]}"; done
  else
    local s; for s in "${services[@]}"; do stop_one "$s"; done
  fi
}

cmd_status() {
  init_home
  local s state
  for s in "${ALL_SERVICES[@]}"; do
    case "$s" in
      postgres) "$PG_BIN/pg_ctl" -D "$H/postgres" status >/dev/null 2>&1 && state="running :$PG_PORT" || state="stopped" ;;
      redis) redis_cli ping 2>/dev/null | grep -q PONG && state="running :$REDIS_PORT" || state="stopped" ;;
      *) alive "$s" && state="running (pid $(pid_of "$s"))" || state="stopped" ;;
    esac
    printf '  %-9s %s\n' "$s" "$state"
  done
  printf '  %-9s %s\n' "health" "$(curl -fsS "http://127.0.0.1:$API_PORT/health" 2>/dev/null || echo unreachable)"
  printf '  %-9s %s\n' "ready" "$(curl -sS "http://127.0.0.1:$API_PORT/ready" 2>/dev/null || echo unreachable)"
}

cmd_logs() {
  init_home
  if [ $# -eq 0 ]; then ls -1 "$LOGS"; return; fi
  local f="$LOGS/$1.log"; [ -f "$f" ] || die "no log for $1 (have: $(ls "$LOGS" | tr '\n' ' '))"
  if [ "${2:-}" = "-f" ]; then tail -n 50 -f "$f"; else tail -n 100 "$f"; fi
}

cmd_test() {
  init_home; write_api_env
  with_api_env "$PY" "$REPO/scripts/local/kiko_local_smoke.py" \
    --api "http://127.0.0.1:$API_PORT" --mailpit "http://127.0.0.1:$MAIL_UI_PORT" \
    --state "$H/smoke" --pg-bin "$PG_BIN" "$@"
}

cmd_desktop_e2e() {
  init_home; write_api_env
  local bin="$REPO/apps/desktop/src-tauri/target/debug/kiko-desktop"
  [ -x "$bin" ] || die "debug build missing: cd apps/desktop && pnpm tauri build --debug --no-bundle"
  # Single-instance app: a running Kiko would receive the launch instead of the test binary.
  pgrep -f "/kiko-desktop" >/dev/null && die "quit the Kiko app first (the journey launches its own copy)"
  # 127.0.0.1 (not localhost) keeps the test's Keychain item apart from your own session.
  (set -a; . "$RUN/api.env"; set +a; PYTHONPATH="$API_DIR" KIKO_API_URL="http://127.0.0.1:$API_PORT" \
    API_PYTHON="$PY" "$REPO/apps/desktop/e2e/run-journey.sh")
}

cmd_open_link() {
  local url="${1:?usage: open-link <emailed link>}" path
  path="${url#http://localhost:$WEB_PORT/}"
  [ "$path" != "$url" ] || path="${url#http://127.0.0.1:$WEB_PORT/}"
  [ "$path" != "$url" ] || die "expected a link starting with http://localhost:$WEB_PORT/"
  case "$path" in
    verify-email\?token=*|reset-password\?token=*|invite\?token=*) open "kiko://$path" ;;
    *) die "only verify-email, reset-password and invite links can be opened in the app" ;;
  esac
}

cmd_env() {
  cat <<EOF
KIKO_LOCAL_HOME=$H
API            http://localhost:$API_PORT
Web            http://localhost:$WEB_PORT
Mailpit UI     http://127.0.0.1:$MAIL_UI_PORT  (SMTP 127.0.0.1:$SMTP_PORT)
PostgreSQL     127.0.0.1:$PG_PORT db=kiko_local user=kiko_local (password in $SECRETS)
Redis          127.0.0.1:$REDIS_PORT (password in $SECRETS)
Python         $PY
EOF
}

case "${1:-}" in
  start) shift; cmd_start "$@" ;;
  stop) shift; cmd_stop "$@" ;;
  restart) shift; cmd_stop "$@"; cmd_start "$@" ;;
  status) cmd_status ;;
  logs) shift; cmd_logs "$@" ;;
  migrate) ensure_tools; init_home; migrate ;;
  test) shift; cmd_test "$@" ;;
  test-persisted) shift; cmd_test --persisted "$@" ;;
  desktop-e2e) cmd_desktop_e2e ;;
  open-link) shift; cmd_open_link "$@" ;;
  psql) init_home; pg_env; exec "$PG_BIN/psql" -h 127.0.0.1 -p "$PG_PORT" -U kiko_local kiko_local ;;
  env) cmd_env ;;
  *) sed -n '2,29p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
